const root = document.documentElement;
const nodes = Array.from(document.querySelectorAll('[data-i18n]'));
const FR = {};
nodes.forEach((n) => { const k = n.getAttribute('data-i18n'); if (!(k in FR)) FR[k] = n.innerHTML; });

let lang = 'fr';
const listeners = [];

export const getLang = () => lang;
export const meta = () => META[lang];
export const onLang = (fn) => { listeners.push(fn); };

export function setLang(next, remember) {
  lang = next === 'en' ? 'en' : 'fr';
  nodes.forEach((n) => {
    const k = n.getAttribute('data-i18n'), v = lang === 'en' ? EN[k] : FR[k];
    if (v != null) n.innerHTML = v;
  });
  const m = META[lang];
  root.lang = lang === 'en' ? 'en-CA' : 'fr-CA';
  document.title = m.title;
  const d = document.querySelector('meta[name="description"]'); if (d) d.setAttribute('content', m.desc);
  const b = document.getElementById('lang'); if (b) { b.textContent = lang === 'en' ? 'FR' : 'EN'; b.setAttribute('aria-label', m.lang); }
  document.querySelectorAll('[data-aria]').forEach((el) => { const v = m[el.dataset.aria]; if (v) el.setAttribute('aria-label', v); });
  if (remember) { try { localStorage.setItem('lang', lang); } catch (e) { /* stockage indisponible */ } }
  root.classList.remove('lang-pending');
  listeners.forEach((fn) => fn(lang));
}

export function initLang() {
  let initial = 'fr';
  try { initial = localStorage.getItem('lang') || 'fr'; } catch (e) { /* stockage indisponible */ }
  if (location.hash === '#en') initial = 'en';
  if (location.hash === '#fr') initial = 'fr';
  setLang(initial, false);
  const b = document.getElementById('lang');
  if (b) b.addEventListener('click', () => setLang(lang === 'fr' ? 'en' : 'fr', true));
}
